import pandas as pd, numpy as np
P='/mnt/share/행정데이터_set/work/report/활용고도화전략/적용사례/data/가상데이터_확대본_n42000.parquet'
df=pd.read_parquet(P)
g=df.groupby('hid')
print('hnum==size', (g['hnum'].transform('size')==df['hnum']).mean())
print('hnum const', (g['hnum'].transform('nunique')==1).mean())
print('h_dinc==sum p_dinc', (g['p_dinc'].transform('sum')==df['h_dinc']).mean())
print('h_prop const', (g['h_prop'].transform('nunique')==1).mean())
print('h_prop==sum p_prop', (g['p_prop'].transform('sum')==df['h_prop']).mean())
print('heads per hid==1', (g['head'].transform(lambda s:(s==1).sum())==1).mean())
print('hhwgt const', (g['hhwgt'].transform('nunique')==1).mean())
# cross checks
def e1(v): return (df[v]==1).fillna(False).astype(bool)
print('disp_yn2==1 & not dis', (e1('disp_yn2') & ~e1('dis_yn')).sum())
print('disp_yn1==1 & not dis', (e1('disp_yn1') & ~e1('dis_yn')).sum())
print('childcare_yn1 & age>6', (e1('childcare_yn1') & (df.age>6)).sum(), 'age dist', df.loc[e1('childcare_yn1'),'age'].value_counts().sort_index().to_dict())
print('childbn_yn2 age dist', df.loc[e1('childbn_yn2'),'age'].value_counts().sort_index().to_dict())
print('ltcare age<65', (e1('ltcare_bn_yn') & (df.age<65)).sum())
print('jobseek outside 18-64', (e1('unempbn_jobseekbn_yn') & ~df.age.between(18,64)).sum())
print('grade1 vs grade2', pd.crosstab(df['dis_grade_1'], df['dis_grade_2'], dropna=False).to_dict())
print('dis_disp_yn', df['dis_disp_yn'].value_counts(dropna=False).to_dict())
print('nbls_edu_yn1 age 7-18', (e1('nbls_edu_yn1') & df.age.between(7,18)).sum(), (e1('nbls_edu_yn1')).sum())
print('aftsch age 7-18', (e1('pubedu_aftsch_yn') & df.age.between(7,18)).sum())
print('oldwork gender', df.loc[e1('oldwork_type1_yn1'),'gender'].value_counts().to_dict())
print('self gender', df.loc[e1('self_yn1'),'gender'].value_counts().to_dict())
print('parentleave gender yn1', df.loc[e1('empins_parentleave_yn1'),'gender'].value_counts().to_dict(), 'yn2', df.loc[e1('empins_parentleave_yn2'),'gender'].value_counts().to_dict())
print('special1 out_fee notna', df.loc[e1('nhi_special1_yn'),'nhi_out_fee'].notna().sum(), e1('nhi_special1_yn').sum())
print('dis out_fee notna', df.loc[e1('dis_yn'),'nhi_out_fee'].notna().sum())
print('ceiling by age65+ missing', df.loc[df.age>=65,'nhi_ceiling_subsidy_yn'].value_counts(dropna=False).to_dict())
print('kua age range', (e1('kua_yn1') & ~df.age.between(18,64)).sum())
print('privschp yn2 gender', df.loc[e1('privschp_yn2'),'gender'].value_counts().to_dict())
print('empins_support_yn2 gender', df.loc[e1('empins_support_yn2'),'gender'].value_counts().to_dict())
print('matleave gender', df.loc[e1('empins_matleave_yn1'),'gender'].value_counts().to_dict())
print('empins_yn2 18-64', df.loc[df.age.between(18,64),'empins_yn2'].value_counts(dropna=False).to_dict())
