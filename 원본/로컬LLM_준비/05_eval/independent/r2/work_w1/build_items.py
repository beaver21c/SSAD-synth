def spec(measure, population, by, unit='person', numerator=None, value_var=None, q=None, alt=None):
    s = {'turn': 1}
    if alt is not None:
        s['alt'] = alt
    s['measure'] = measure
    s['unit'] = unit
    s['population'] = population
    if numerator is not None:
        s['numerator'] = numerator
    if value_var is not None:
        s['value_var'] = value_var
    if q is not None:
        s['q'] = q
    s['by'] = by
    return s


def std(name):
    return {'std': name}


def bins(var, cuts, labels):
    return {'var': var, 'bins': cuts, 'labels': labels}


def cat(var):
    return {'cat': var}


def groups(*pairs):
    return {'groups': [{'label': l, 'cond': c} for l, c in pairs]}


