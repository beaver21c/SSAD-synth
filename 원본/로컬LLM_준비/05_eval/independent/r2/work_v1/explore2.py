import pandas as pd, numpy as np
P='/mnt/share/행정데이터_set/work/report/활용고도화전략/적용사례/data/가상데이터_확대본_n42000.parquet'
df=pd.read_parquet(P)
g=df.groupby('hid')
cnt=g['hid'].transform('size')
print('hnum==rows per hid:', (cnt==df['hnum']).mean(), ' hnum nunique within hid max:', g['hnum'].nunique().max())
hs=g['p_dinc'].transform('sum')
print('h_dinc == sum p_dinc:', (hs==df['h_dinc']).mean(), ' h_dinc nunique within hid max', g['h_dinc'].nunique().max())
print('heads per hid:', g['head'].apply(lambda s:(s==1).sum()).value_counts().to_dict())
print('sido nunique within hid max', g['sido'].nunique().max())
# deposit
hd=g['p_ee_deposit_amt_ptot'].transform('sum')
print('h_ee == sum p_ee:', (hd==df['h_ee_deposit_amt_ptot']).mean())
hd2=g['ee_deposit_amt_ptot'].transform('sum')
print('h_ee == sum ee (float):', (np.isclose(hd2,df['h_ee_deposit_amt_ptot'])).mean())
print('p_ee == ee fillna0:', (df['p_ee_deposit_amt_ptot']==df['ee_deposit_amt_ptot'].fillna(0)).mean(), 'max abs diff', (df['p_ee_deposit_amt_ptot']-df['ee_deposit_amt_ptot'].fillna(0)).abs().max())
hp=g['p_prop'].transform('sum')
print('h_prop == sum p_prop:', (hp==df['h_prop']).mean())
pp=df['p_ptax_land']+df['p_ptax_housing']+df['p_ptax_building']+df['p_ee_deposit_amt_ptot']
print('p_prop == sum comps:', (pp==df['p_prop']).mean(), (pp-df['p_prop']).abs().max())
# dainc
m=df['dainc_sum'].notna()
print('dainc_sum notna & p_dainc>0 same set:', ((df['p_dainc']>0)==m).mean())
d=(df.loc[m,'p_dainc']-df.loc[m,'dainc_sum'])
print('p_dainc - dainc_sum: eq share', (d.abs()<1).mean(), 'ratio q', (df.loc[m,'p_dainc']/df.loc[m,'dainc_sum']).quantile([0,.1,.5,.9,1]).round(4).to_dict())
d2=(df.loc[m,'p_dainc']-(df.loc[m,'dainc_sum']+df.loc[m,'dainc_taxfree'].fillna(0)))
print('p_dainc - (sum+taxfree): eq share', (d2.abs()<1).mean())
print('p_dainc top values count', df.loc[m,'p_dainc'].value_counts().head(5).to_dict())
# ltcare
print(pd.crosstab(df['ltcare_grade'].astype('float').fillna(-1), df['ltcare_visit_yn'].astype('float').fillna(-1)))
print(pd.crosstab(df['ltcare_grade'].astype('float').fillna(-1), df['ltcare_bn_yn'].astype('float').fillna(-1)))
print('visit yn1 & freq>0:', ((df['ltcare_visit_yn']==1).fillna(False) == (df['ltcare_visit_freq']>0).fillna(False)).mean())
print('inst yn1 & freq>0:', ((df['ltcare_institute_yn']==1).fillna(False) == (df['ltcare_institute_freq']>0).fillna(False)).mean())
print('ltcare_bn age<65:', ((df['ltcare_bn_yn']==1)&(df['age']<65)).sum())
# various consistency
def same(a,b,name): print(name, (a==b).mean())
same(df['disp_bn_yn1'].eq(1), df['disp_bn_amt'].notna(), 'disp_bn yn1 vs amt notna')
same(df['milp_yn1'].eq(1), df['milp_premium_amt'].notna(), 'milp yn1 vs prem notna')
same(df['empins_matleave_yn1'].eq(1), df['empins_matleave_dur'].notna(), 'mat yn1 vs dur')
same(df['empins_matleave_yn1'].eq(1), df['empins_matleave_amt'].notna(), 'mat yn1 vs amt')
same(df['pubedu_aftsch_yn'].eq(1), df['pubedu_aftsch_amt'].notna(), 'aftsch')
same(df['privschp_pension_yn'].eq(1), df['privschp_pension_amt'].notna(), 'privschp pension')
same(df['nbls_edu_yn1'].eq(1), df['nbls_edu_amt1'].notna(), 'edu')
print('age range by var:')
for v,cond in [('childcare_yn1',df['childcare_yn1'].eq(1)),('childcare_yn2',df['childcare_yn2'].eq(1)),('carebn_yn2',df['carebn_yn2'].eq(1)),('childbn_yn2',df['childbn_yn2'].eq(1)),('pubedu',df['pubedu_aftsch_yn'].eq(1)),('nbls_edu_amt1',df['nbls_edu_amt1'].notna()),('bp_yn1',df['bp_yn1'].eq(1)),('disp_bn',df['disp_bn_yn1'].eq(1)),('disp_yn1',df['disp_yn1'].eq(1)),('oldcare2',df['oldcare_yn2'].eq(1)),('matleave',df['empins_matleave_yn1'].eq(1)),('milp',df['milp_yn1'].eq(1)),('dis_yn',df['dis_yn'].eq(1))]:
    a=df.loc[cond,'age']
    print(' ',v, a.min(), a.max(), 'n',len(a))
print('matleave gender', df.loc[df['empins_matleave_yn1'].eq(1),'gender'].value_counts().to_dict())
print('spouseleave gender', df.loc[df['empins_spouseleave_yn1'].eq(1),'gender'].value_counts().to_dict())
print('childcare age dist yn1', df.loc[df['childcare_yn1'].eq(1),'age'].value_counts().sort_index().to_dict())
print('childcare age dist yn2', df.loc[df['childcare_yn2'].eq(1),'age'].value_counts().sort_index().to_dict())
print('bp type by yn2'); print(pd.crosstab(df['bp_yn2'], df['bp_type']))
print('nhi_highbp by age65', pd.crosstab(df['age']>=65, df['nhi_highbp_yn'].fillna(-1)).to_dict())
print('nhi_in_dur notna vs highbp notna', pd.crosstab(df['nhi_in_dur'].notna(), df['nhi_highbp_yn'].notna()).to_dict())
print('evou among single 65+ live yn2 heads', ((df['head']==1)&(df['hnum']==1)&(df['age']>=65)&df['nbls_live_yn2'].eq(1)).sum())
print('hnum1 head', df.loc[df['hnum']==1,'head'].value_counts().to_dict())
print('jeju aid', (df['aid_live_yn1'].eq(1)&(df['sido']==17)).sum())
print('dtypes Int64 cols:', [c for c in df.columns if str(df[c].dtype)=='Int64'][:80])
