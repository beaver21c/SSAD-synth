import pandas as pd, numpy as np
P='/mnt/share/행정데이터_set/work/report/활용고도화전략/적용사례/data/가상데이터_확대본_n42000.parquet'
df=pd.read_parquet(P)
g=df.groupby('hid')
print('hnum==rows', (g['hnum'].first()==g.size()).mean(), 'hnum nunique max', g['hnum'].nunique().max())
print('h_dinc==sum p_dinc', (g['p_dinc'].sum()==g['h_dinc'].first()).mean(), 'h_dinc nunique max', g['h_dinc'].nunique().max())
print('h_prop==sum p_prop', (g['p_prop'].sum()==g['h_prop'].first()).mean(), 'h_prop nunique max', g['h_prop'].nunique().max())
print('hhwgt nunique max', g['hhwgt'].nunique().max(), 'sido nunique max', g['sido'].nunique().max())
print('heads per hh', g['head'].apply(lambda s:(s==1).sum()).value_counts().to_dict())
m1=df['nbls_medi_yn2']==1; m2=df['nhi_type'].isin([7,8])
print('medi yn2 vs nhi_type', (m1&m2).sum(), (m1&~m2).sum(), (~m1&m2).sum())
d=df[df['dis_yn']==1]
print('dis grade1 x grade2', pd.crosstab(d['dis_grade_1'], d['dis_grade_2'].fillna(-1)).to_dict())
print('childcare age', df.loc[df['childcare_yn1']==1,'age'].value_counts().sort_index().to_dict())
print('aftsch age', df.loc[df['pubedu_aftsch_yn']==1,'age'].value_counts().sort_index().to_dict())
print('oldcare age<65', (df.loc[df['oldcare_yn2']==1,'age']<65).sum(), 'age==65', (df.loc[df['oldcare_yn2']==1,'age']==65).sum())
print('oldwork age<65', (df.loc[df['oldwork_type1_yn1']==1,'age']<65).sum())
print('ltcare bn age<65', (df.loc[df['ltcare_bn_yn']==1,'age']<65).sum())
print('disvou & not dis', ((df['disvou_act_yn1']==1)&(df['dis_yn']!=1)).sum())
print('evou&live2', ((df['evou_yn']==1)&(df['nbls_live_yn2']==1)).sum())
print('itc_amt notna & itc_yn', pd.crosstab(df['itc_yn'].fillna(-1), df['itc_amt'].notna()).to_dict())
print('pension overlaps', ((df['govp_pension_yn']==1)&(df['privschp_pension_yn']==1)).sum(), ((df['govp_pension_yn']==1)&(df['milip_pension_yn']==1)).sum(), ((df['privschp_pension_yn']==1)&(df['milip_pension_yn']==1)).sum())
print('kua_type among yn2==1', df.loc[df['kua_yn2']==1,'kua_type'].value_counts(dropna=False).to_dict())
print('medi type by yn2', df.loc[df['nbls_medi_yn2']==1,'nbls_medi_type'].value_counts(dropna=False).to_dict())
print('empins_yn2 cols like', [c for c in df.columns if c.startswith('empins_yn')])
